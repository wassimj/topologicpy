    @staticmethod
    def Model(file, sourcePath: str = None, silent: bool = False):
        """
        Returns an in-memory IFCModel from the input IFC source.

        This convenience method accepts an existing IFCModel, a parsed entity
        dictionary, a path, STEP text, or a serialisable IFC file-like object.
        Existing IFCModel inputs are returned unchanged.

        Parameters
        ----------
        file : IFCModel, dict, str, or file-like object
            The input IFC source.
        sourcePath : str , optional
            Source path associated with a raw entity dictionary or STEP text.
            Default is None.
        silent : bool , optional
            If True, suppresses errors and warnings. Default is False.

        Returns
        -------
        IFCModel
            The resulting in-memory model, or None if the input cannot be read.
        """
        if isinstance(file, IFCModel):
            return file

        if isinstance(file, dict):
            return IFC.ModelByEntities(
                file,
                sourcePath=sourcePath,
                silent=silent,
            )

        if isinstance(file, str):
            if os.path.exists(file):
                return IFC.ModelByPath(file, silent=silent)
            if "ISO-10303-21" in file:
                entities = IFCFastTopology.ParseText(file, silent=silent)
                header, schema = IFC._step_header_and_schema(file)
                return IFC.ModelByEntities(
                    entities,
                    sourcePath=sourcePath,
                    schema=schema,
                    header=header,
                    silent=silent,
                )

        text = IFCFastTopology._file_to_step_text(file)
        if text:
            entities = IFCFastTopology.ParseText(text, silent=silent)
            header, schema = IFC._step_header_and_schema(text)
            return IFC.ModelByEntities(
                entities,
                sourcePath=sourcePath,
                schema=schema,
                header=header,
                silent=silent,
            )

        if not silent:
            print("IFC.Model - Error: Could not read or parse the input IFC source. Returning None.")
        return None

    @staticmethod
    def ModelByEntities(
        entities,
        sourcePath: str = None,
        schema: str = None,
        header: str = None,
        silent: bool = False,
    ):
        """
        Wraps a parsed IFC entity dictionary in an IFCModel.

        The entity dictionary is retained by reference and is not copied.

        Parameters
        ----------
        entities : dict
            Parsed IFC entities keyed by STEP id.
        sourcePath : str , optional
            Original IFC source path. Default is None.
        schema : str , optional
            IFC schema identifier. Default is None.
        header : str , optional
            Preserved STEP HEADER section. Default is None.
        silent : bool , optional
            If True, suppresses errors and warnings. Default is False.

        Returns
        -------
        IFCModel
            The wrapped in-memory IFC model, or None if entities is invalid.
        """
        if isinstance(entities, IFCModel):
            return entities

        if not isinstance(entities, dict):
            if not silent:
                print(
                    "IFC.ModelByEntities - Error: entities must be a dictionary. "
                    "Returning None."
                )
            return None

        for key, entity in entities.items():
            if not isinstance(key, int) or not isinstance(entity, IFCFastEntity):
                if not silent:
                    print(
                        "IFC.ModelByEntities - Error: entities must be keyed by "
                        "integer STEP ids and contain IFCFastEntity values. "
                        "Returning None."
                    )
                return None

        try:
            return IFCModel(
                entities=entities,
                sourcePath=sourcePath,
                schema=schema,
                header=header,
            )
        except Exception as error:
            if not silent:
                print(
                    "IFC.ModelByEntities - Error: Could not create the IFCModel: "
                    f"{error}. Returning None."
                )
            return None

    @staticmethod
    def ModelByPath(path: str, silent: bool = False):
        """
        Parses an IFC STEP file once and returns an in-memory IFCModel.

        Parameters
        ----------
        path : str
            Path to the IFC STEP file.
        silent : bool , optional
            If True, suppresses errors and warnings. Default is False.

        Returns
        -------
        IFCModel
            The parsed in-memory IFC model, or None if parsing fails.
        """
        if not isinstance(path, str) or not path.strip() or not os.path.isfile(path):
            if not silent:
                print("IFC.ModelByPath - Error: Invalid IFC path. Returning None.")
            return None

        path = os.path.abspath(path)
        try:
            with open(path, "rb") as file:
                data = file.read()
        except Exception as error:
            if not silent:
                print(
                    "IFC.ModelByPath - Error: Could not read the IFC file: "
                    f"{error}. Returning None."
                )
            return None

        entities = IFCFastTopology.ParseBytes(data, silent=silent)
        if not isinstance(entities, dict) or not entities:
            if not silent:
                print("IFC.ModelByPath - Error: Could not parse IFC entities. Returning None.")
            return None

        text = data.decode("utf-8", errors="ignore")
        header, schema = IFC._step_header_and_schema(text)
        return IFC.ModelByEntities(
            entities,
            sourcePath=path,
            schema=schema,
            header=header,
            silent=silent,
        )

