    @staticmethod
    def Summary(model, silent: bool = False) -> dict:
        """Returns a cached compact summary of an IFCModel."""
        model = IFC._model_from_input(model, silent=silent)
        if not isinstance(model, IFCModel):
            return None
        cache_key = "default"
        if cache_key in model.summaryCache:
            return model.summaryCache[cache_key]
        entities = model.entities
        products = IFCFastTopology.ProductsByEntities(entities)
        type_counts = {}
        product_counts = {}
        rep_counts = {}
        item_counts = {}
        for entity in entities.values():
            type_counts[entity.type] = type_counts.get(entity.type, 0) + 1
            if entity.type == "IFCSHAPEREPRESENTATION":
                rep_id = IFCFastTopology._as_string(
                    entity.args[1] if len(entity.args) > 1 else None
                )
                rep_type = IFCFastTopology._as_string(
                    entity.args[2] if len(entity.args) > 2 else None
                )
                rep_counts[(rep_id, rep_type)] = rep_counts.get((rep_id, rep_type), 0) + 1
                for reference in IFCFastTopology._refs_in_value(
                    entity.args[3] if len(entity.args) > 3 else None
                ):
                    item = IFCFastTopology._entity_from_ref(reference, entities)
                    if item is not None:
                        item_counts[item.type] = item_counts.get(item.type, 0) + 1
        for product in products:
            product_counts[product.type] = product_counts.get(product.type, 0) + 1
        result = {
            "model_id": model.modelId,
            "revision": model.revision,
            "source": model.sourcePath,
            "schema": model.schema,
            "entity_count": len(entities),
            "product_count": len(products),
            "entity_type_counts": dict(sorted(type_counts.items())),
            "product_type_counts": dict(sorted(product_counts.items())),
            "shape_representation_counts": {
                str(key): value
                for key, value in sorted(rep_counts.items(), key=lambda item: str(item[0]))
            },
            "representation_item_counts": dict(sorted(item_counts.items())),
        }
        model.summaryCache[cache_key] = result
        return result

    @staticmethod
    def MeshData(
        model,
        includeTypes: list = [],
        excludeTypes: list = [],
        dictionaryMode: str = "basic",
        circleSides: int = 24,
        scale: float = 1.0,
        ontology: bool = True,
        silent: bool = False,
    ) -> dict:
        """Returns aggregated mesh data using IFCModel geometry caches."""
        model = IFC._model_from_input(model, silent=silent)
        if not isinstance(model, IFCModel):
            return None
        products = IFCFastTopology.ProductsByEntities(
            model.entities,
            includeTypes,
            excludeTypes,
        )
        metadata_cache = IFC._model_metadata_cache(model, dictionaryMode)
        vertices, edges, faces, vertex_dictionaries, product_ranges = [], [], [], [], []
        for product in products:
            mesh = IFC._model_mesh_data(
                model,
                product,
                circleSides=circleSides,
                scale=scale,
            )
            if not mesh or not mesh.get("vertices"):
                continue
            dictionary = IFCFastTopology._entity_dictionary(
                product,
                dictionaryMode,
                metadataCache=metadata_cache,
                ontology=ontology,
                source=model.sourcePath,
                generatedBy="IFC.MeshData",
            )
            v0, e0, f0 = len(vertices), len(edges), len(faces)
            product_vertices = mesh.get("vertices") or []
            vertices.extend(product_vertices)
            vertex_dictionaries.extend([dictionary] * len(product_vertices))
            edges.extend([[a + v0, b + v0] for a, b in (mesh.get("edges") or [])])
            faces.extend([[index + v0 for index in face] for face in (mesh.get("faces") or [])])
            product_ranges.append({
                "id": product.id,
                "type": product.type,
                "global_id": IFCFastTopology._root_attr(product, 0),
                "name": IFCFastTopology._root_attr(product, 2),
                "start": v0,
                "end": len(vertices),
                "edge_start": e0,
                "edge_end": len(edges),
                "face_start": f0,
                "face_end": len(faces),
            })
        return {
            "vertices": vertices,
            "edges": edges,
            "faces": faces,
            "vertex_dictionaries": vertex_dictionaries,
            "product_ranges": product_ranges,
        }

