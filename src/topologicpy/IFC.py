    @staticmethod
    def _entities_from_input(file, silent: bool = False):
        if isinstance(file, IFCModel):
            return file.entities
        if isinstance(file, dict):
            return file
        if isinstance(file, str):
            if os.path.exists(file):
                return IFCFastTopology.Parse(file, silent=silent)
            if "ISO-10303-21" in file:
                return IFCFastTopology.ParseText(file, silent=silent)
            return None
        text = IFCFastTopology._file_to_step_text(file)
        if text:
            return IFCFastTopology.ParseText(text, silent=silent)
        return None

    @staticmethod
    def _step_header_and_schema(text: str):
        """Returns the preserved STEP HEADER section and first IFC schema name."""
        if not isinstance(text, str) or not text:
            return None, None

        upper = text.upper()
        header_start = upper.find("HEADER;")
        data_start = upper.find("DATA;")
        header = None

        if header_start >= 0 and data_start > header_start:
            header = text[header_start:data_start].strip()

        search_text = header if header is not None else text
        match = re.search(
            r"FILE_SCHEMA\s*\(\s*\(\s*'([^']+)'",
            search_text,
            flags=re.IGNORECASE | re.DOTALL,
        )
        schema = match.group(1).strip().upper() if match else None
        return header, schema

    @staticmethod
    def _display_type(entity_type: str) -> str:
        return IFCFastTopology._ifc_display_class(entity_type) or str(entity_type or "")

    @staticmethod
    def _value_contains_ref(value, ref) -> bool:
        if value == ref:
            return True
        if isinstance(value, list):
            return any(IFC._value_contains_ref(v, ref) for v in value)
        if isinstance(value, tuple):
            return any(IFC._value_contains_ref(v, ref) for v in value)
        return False
