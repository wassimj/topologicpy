@dataclass
class IFCFastEntity:
    id: int
    type: str
    args: list

    def is_a(self, name: Optional[str] = None):
        if name is None:
            return self.type
        return self.type.lower() == str(name).lower()

    def __repr__(self):
        return f"#{self.id}={self.type}(...)"

@dataclass
class IFCModel:
    """
    Stores one parsed IFC document in memory.

    The model owns the parsed ``IFCFastEntity`` dictionary together with source
    metadata and caches that can be reused by subsequent IFC operations. The
    input entity dictionary is retained by reference rather than copied so that
    future semantic and exporter operations can modify one shared in-memory
    model.

    Parameters
    ----------
    entities : dict
        Parsed IFC entities keyed by STEP id.
    sourcePath : str , optional
        Original IFC path, when known. Default is None.
    schema : str , optional
        IFC schema identifier, such as ``IFC2X3`` or ``IFC4``. Default is None.
    header : str , optional
        Preserved STEP HEADER section. Default is None.
    modelId : str , optional
        Unique identifier for this in-memory model. A UUID is generated by
        default.
    revision : int , optional
        In-memory model revision. Default is 0.
    dirty : bool , optional
        Indicates whether the model differs from its source. Default is False.

    Notes
    -----
    ``nextEntityId`` is initialized to one greater than the largest existing
    STEP id. The cache dictionaries are intentionally empty at creation and will
    be populated lazily by later stages of the IFC API refactor.
    """

    entities: Dict[int, IFCFastEntity]
    sourcePath: Optional[str] = None
    schema: Optional[str] = None
    header: Optional[str] = None
    modelId: str = field(default_factory=lambda: uuid.uuid4().hex)
    revision: int = 0
    dirty: bool = False
    metadataCache: Dict[Any, Any] = field(default_factory=dict, repr=False)
    placementCache: Dict[Any, Any] = field(default_factory=dict, repr=False)
    meshCache: Dict[Any, Any] = field(default_factory=dict, repr=False)
    topologyCache: Dict[Any, Any] = field(default_factory=dict, repr=False)
    propertyCache: Dict[Any, Any] = field(default_factory=dict, repr=False)
    tripleCache: Dict[Any, Any] = field(default_factory=dict, repr=False)
    summaryCache: Dict[Any, Any] = field(default_factory=dict, repr=False)
    indexes: Dict[str, Any] = field(default_factory=dict, repr=False)
    nextEntityId: int = field(init=False)

    def __post_init__(self):
        if not isinstance(self.entities, dict):
            raise TypeError("IFCModel.entities must be a dictionary.")

        if isinstance(self.sourcePath, str) and self.sourcePath.strip():
            self.sourcePath = os.path.abspath(self.sourcePath.strip())
        else:
            self.sourcePath = None

        if self.schema is not None:
            schema = str(self.schema).strip().upper()
            self.schema = schema or None

        if self.header is not None:
            header = str(self.header).strip()
            self.header = header or None

        self.modelId = str(self.modelId or uuid.uuid4().hex)
        self.revision = max(0, int(self.revision or 0))
        self.dirty = bool(self.dirty)
        self.nextEntityId = max(
            (key for key in self.entities if isinstance(key, int)),
            default=0,
        ) + 1

    def __contains__(self, entityId):
        return entityId in self.entities

    def __getitem__(self, entityId):
        return self.entities[entityId]

    def __len__(self):
        return len(self.entities)

    def __repr__(self):
        source = self.sourcePath or "<memory>"
        schema = self.schema or "UNKNOWN"
        return (
            f"<IFCModel schema={schema} entities={len(self.entities)} "
            f"revision={self.revision} source={source!r}>"
        )

    def get(self, entityId, default=None):
        """Returns the entity at the input STEP id."""
        return self.entities.get(entityId, default)

    def items(self):
        """Returns the model entity items view."""
        return self.entities.items()

    def keys(self):
        """Returns the model entity keys view."""
        return self.entities.keys()

    def values(self):
        """Returns the model entity values view."""
        return self.entities.values()

    def invalidateCaches(self, geometry: bool = False):
        """Invalidates cached data after an in-memory model modification."""
        self.metadataCache.clear()
        self.propertyCache.clear()
        self.tripleCache.clear()
        self.summaryCache.clear()
        self.indexes.clear()
        if geometry:
            self.placementCache.clear()
            self.meshCache.clear()
            self.topologyCache.clear()
        return self

    def touch(self, geometry: bool = False):
        """Marks the model as modified and invalidates affected caches."""
        self.revision += 1
        self.dirty = True
        self.nextEntityId = max(
            self.nextEntityId,
            max((key for key in self.entities if isinstance(key, int)), default=0) + 1,
        )
        self.invalidateCaches(geometry=geometry)
        return self

class IFCEntity:
    """
    Lightweight dynamic wrapper around an IFCFastEntity.

    This class exposes IFC root attributes, extracted properties,
    quantities, classifications, materials, and type information
    through Python attribute access.

    Example
    -------
    wall = IFC.Object(file, globalId)

    print(wall.GlobalId)
    print(wall.Name)
    print(wall.FireRating)
    print(wall.Materials)
    """

    _ROOT_ATTRS = {
        "GlobalId": 0,
        "OwnerHistory": 1,
        "Name": 2,
        "Description": 3,
    }

    def __init__(self, entity, entities=None, properties=None):
        self._entity = entity
        self._entities = entities or {}
        self._properties = properties or {}

    def __repr__(self):
        gid = self.GlobalId or ""
        return f"<{self.IFCType} #{self.IFCId} {gid}>"

    @property
    def IFCId(self):
        return self._entity.id if self._entity is not None else None

    @property
    def IFCKey(self):
        return f"#{self._entity.id}" if self._entity is not None else None

    @property
    def IFCType(self):
        if self._entity is None:
            return None

        t = self._entity.type

        if str(t).upper().startswith("IFC"):
            return "Ifc" + str(t)[3:].lower().title().replace("_", "")

        return t

    @property
    def Entity(self):
        """
        Returns the wrapped IFCFastEntity.
        """
        return self._entity

    @property
    def Properties(self):
        return self._properties.get("properties", {})

    @property
    def TypeProperties(self):
        return self._properties.get("type_properties", {})

    @property
    def Quantities(self):
        return self._properties.get("quantities", {})

    @property
    def TypeQuantities(self):
        return self._properties.get("type_quantities", {})

    @property
    def Classifications(self):
        return self._properties.get("classifications", [])

    @property
    def Materials(self):
        return self._properties.get("materials", [])

    @property
    def Type(self):
        return self._properties.get("type", None)

    def is_a(self, name=None):
        if self._entity is None:
            return None if name is None else False

        return self._entity.is_a(name)

    def Attribute(self, name, default=None):
        """
        Returns an attribute/property safely.
        """

        try:
            return getattr(self, name)
        except Exception:
            return default

    def ToDict(self):
        """
        Returns a serializable dictionary representation.
        """

        return {
            "ifc_id": self.IFCId,
            "ifc_key": self.IFCKey,
            "ifc_type": self.IFCType,
            "global_id": self.GlobalId,
            "name": self.Name,
            "description": self.Description,
            "properties": self.Properties,
            "type_properties": self.TypeProperties,
            "quantities": self.Quantities,
            "type_quantities": self.TypeQuantities,
            "classifications": self.Classifications,
            "materials": self.Materials,
            "type": self.Type,
        }

    def _normalise_name(self, value):
        if value is None:
            return ""

        return "".join(
            ch for ch in str(value).strip().lower()
            if ch.isalnum()
        )

    def _lookup_in_grouped_dict(self, grouped, name):
        """
        Searches grouped property dictionaries.

        Supports:
        - FireRating
        - Pset_WallCommon.FireRating
        """

        target = self._normalise_name(name)

        if not isinstance(grouped, dict):
            return None

        # Direct property search.
        for group_name, values in grouped.items():
            if not isinstance(values, dict):
                continue

            for key, value in values.items():
                if self._normalise_name(key) == target:
                    return value

        # Qualified search.
        if "." in str(name):
            group_part, key_part = str(name).split(".", 1)

            group_target = self._normalise_name(group_part)
            key_target = self._normalise_name(key_part)

            for group_name, values in grouped.items():
                if self._normalise_name(group_name) != group_target:
                    continue

                if not isinstance(values, dict):
                    continue

                for key, value in values.items():
                    if self._normalise_name(key) == key_target:
                        return value

        return None

    def __getattr__(self, name):
        """
        Dynamic IFC-style attribute lookup.

        Lookup order:
        1. IFC root attributes
        2. instance properties
        3. type properties
        4. instance quantities
        5. type quantities
        """

        # IFC root attributes.
        if name in IFCEntity._ROOT_ATTRS:
            index = IFCEntity._ROOT_ATTRS[name]

            try:
                return IFCFastTopology._root_attr(self._entity, index)
            except Exception:
                return None

        # Instance properties.
        value = self._lookup_in_grouped_dict(
            self.Properties,
            name
        )

        if value is not None:
            return value

        # Type properties.
        value = self._lookup_in_grouped_dict(
            self.TypeProperties,
            name
        )

        if value is not None:
            return value

        # Instance quantities.
        value = self._lookup_in_grouped_dict(
            self.Quantities,
            name
        )

        if value is not None:
            return value

        # Type quantities.
        value = self._lookup_in_grouped_dict(
            self.TypeQuantities,
            name
        )

        if value is not None:
            return value

        raise AttributeError(
            f"{self.IFCType} has no attribute '{name}'"
        )

